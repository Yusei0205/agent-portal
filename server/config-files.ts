/**
 * Configuration: the project's own .claude and .kiro folders as files, for people who want to edit agents, skills,
 * steering, commands and settings directly rather than through the Agents and skills forms.
 *
 * Every change is committed to the project's git repository, so it can be traced and restored. Files that can run
 * commands on the portal server or loosen approvals (settings files, hooks, Kiro settings and MCP config) can only be
 * changed by admins, and so can the hooks and MCP servers inside Kiro agents and the hooks, MCP servers and
 * permission modes in the frontmatter of Claude agents and skills. The portal's own generated Kiro
 * profiles (.kiro/agents/agent-portal-*) are neither shown nor editable. JSON is checked before it is saved.
 */
import fs from 'node:fs';
import path from 'node:path';
import JSZip from 'jszip';
import { del, get, post, put, sendFile, type Ctx } from './http.ts';
import { commitProject, notifyProject, projectDir, requireProject, type Project } from './projects.ts';
import { HttpError, badRequest, notFound, str } from './util.ts';
import { mustKeepKiroCommands } from './kiro-agents.ts';

export const CONFIG_ROOTS = ['.claude', '.kiro'] as const;
const MAX_FILE = 512 * 1024;
const MAX_FILES = 2000;
const MAX_IMPORT = 20 * 1024 * 1024;

/** Paths only admins may change: they can run commands on the server (hooks, MCP servers) or loosen approvals. */
export function isProtected(rel: string): boolean {
  const p = rel.replace(/\\/g, '/').toLowerCase();
  return (
    /^\.claude\/settings(\.local)?\.json$/.test(p) ||
    /(^|\/)hooks(\/|$)/.test(p) ||
    /^\.kiro\/settings(\/|$)/.test(p) ||
    /(^|\/)\.?mcp\.json$/.test(p)
  );
}

/** The portal's own per-run Kiro profiles: generated and deleted by runs. */
function isGenerated(rel: string): boolean {
  return /^\.kiro\/agents\/agent-portal-[^/]*$/.test(rel.replace(/\\/g, '/'));
}

/** A path inside .claude or .kiro, normalised to forward slashes; anything else is refused. */
export function checkPath(raw: unknown): string {
  const rel = str(raw, 'Path', { max: 300 }).trim().replace(/\\/g, '/').replace(/\/+$/, '');
  const parts = rel.split('/');
  if (!CONFIG_ROOTS.includes(parts[0] as any) || parts.some((x) => !x || x === '.' || x === '..') || /[\0<>:"|?*]/.test(rel)) {
    throw badRequest('Use a path inside .claude/ or .kiro/');
  }
  // Windows drops a trailing dot or space and opens 8.3 short names (SETTIN~1.JSO), so such a name could reach
  // another file, including an admin-only one, without matching the checks below.
  if (parts.some((x) => /[. ]$/.test(x) || x.includes('~'))) throw badRequest('File and folder names cannot end with a dot or a space, or contain ~');
  if (isGenerated(rel)) throw badRequest('That file is generated by the portal for a run and cannot be edited');
  return rel;
}

function abs(project: Project, rel: string): string {
  const base = projectDir(project);
  const full = path.resolve(base, rel);
  if (!full.startsWith(path.resolve(base, rel.split('/')[0]) + path.sep) && full !== path.resolve(base, rel.split('/')[0])) throw badRequest('Path is outside the folder');
  return full;
}

function mustChange(ctx: Ctx, rel: string): void {
  if (isProtected(rel) && ctx.apiToken) throw new HttpError(403, `${rel} can only be changed from a signed-in browser, never with an API token`);
  if (isProtected(rel) && !ctx.user!.is_admin) {
    throw new HttpError(403, `Only admins can change ${rel}: settings, hooks and MCP configuration can run commands on the portal server or skip approvals.`);
  }
}

/**
 * Frontmatter fields of Claude agents, skills and commands that run commands on the server (hooks, MCP servers) or
 * skip approvals (permissionMode). Compared in lower case without separators, so mcpServers, mcp-servers and
 * mcp_servers all count.
 */
const COMMAND_FIELDS = new Set(['hooks', 'mcpservers', 'permissionmode']);

/** True for a frontmatter key that runs commands or skips approvals (hooks, mcpServers, permissionMode in any spelling). */
export function isCommandField(key: string): boolean {
  return COMMAND_FIELDS.has(key.toLowerCase().replace(/[-_]/g, ''));
}

/**
 * The text of a Markdown file's frontmatter fields that run commands or skip approvals (each key line with its
 * indented lines), for comparing two versions of a file. Frontmatter this simple reader cannot follow (flow style,
 * anchors, merge keys) is returned whole, so changing any of it is treated as changing those fields.
 */
export function frontmatterCommandFields(text: string): string {
  const m = /^\uFEFF?---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/.exec(text);
  if (!m) return '';
  const out: string[] = [];
  let keep = false;
  for (const line of m[1].split(/\r?\n/)) {
    if (/^\s*(#.*)?$/.test(line)) continue; // blank lines and comments
    const key = /^["']?([A-Za-z0-9_-]+)["']?[ \t]*:(?:[ \t]|$)/.exec(line)?.[1];
    if (key !== undefined) keep = isCommandField(key);
    else if (!/^[ \t]/.test(line) && !/^-[ \t]/.test(line)) return m[1].trim(); // not a plain "key: value" layout
    if (keep) out.push(line.trimEnd());
  }
  return out.join('\n');
}

/** Only admins (signed in, not with an API token) may add or change frontmatter that runs commands or skips approvals. */
export function mustKeepFrontmatterCommands(ctx: Ctx, rel: string, before: string, after: string): void {
  if (frontmatterCommandFields(before) === frontmatterCommandFields(after)) return;
  if (ctx.apiToken) throw new HttpError(403, `The hooks, MCP servers and permission mode of ${rel} can only be changed from a signed-in browser, never with an API token`);
  if (!ctx.user!.is_admin) {
    throw new HttpError(403, `Only admins can change the hooks, mcpServers or permissionMode of ${rel}: hooks and MCP servers run commands on the portal server, and a permission mode can skip approvals.`);
  }
}

/** Hooks, MCP servers and permission modes in agents and skills run commands on the server or skip approvals: changing them needs an admin. */
function mustKeepAgentCommands(ctx: Ctx, project: Project, rel: string, content: string): void {
  const read = (): string | null => {
    try {
      return fs.readFileSync(abs(project, rel), 'utf8');
    } catch {
      return null; // a new file
    }
  };
  if (/^\.claude\/.+\.md$/i.test(rel)) {
    mustKeepFrontmatterCommands(ctx, rel, read() ?? '', content);
    return;
  }
  if (!/^\.kiro\/agents(-disabled)?\/[^/]+\.json$/.test(rel)) return;
  let before: Record<string, unknown> | null = null;
  try {
    before = JSON.parse(read() ?? '');
  } catch {
    /* a new file */
  }
  mustKeepKiroCommands(ctx, before, JSON.parse(content) ?? {});
}

/** Refuse content the engines could not read. */
function checkContent(rel: string, content: string): void {
  if (Buffer.byteLength(content) > MAX_FILE) throw badRequest('That file is larger than 512 KB');
  if (rel.toLowerCase().endsWith('.json')) {
    try {
      JSON.parse(content);
    } catch (e: any) {
      throw badRequest(`${rel} is not valid JSON: ${String(e?.message ?? e).slice(0, 200)}`);
    }
  }
}

interface Entry {
  path: string;
  dir: boolean;
  size: number;
  protected: boolean;
}

export function listConfig(project: Project, root: string): Entry[] {
  const out: Entry[] = [];
  const base = projectDir(project);
  const walk = (rel: string, depth: number) => {
    if (depth > 8 || out.length >= MAX_FILES) return;
    const dir = path.join(base, rel);
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => Number(b.isDirectory()) - Number(a.isDirectory()) || a.name.localeCompare(b.name))) {
      const r = `${rel}/${e.name}`;
      if (isGenerated(r)) continue;
      if (e.isDirectory()) {
        out.push({ path: r, dir: true, size: 0, protected: isProtected(r) });
        walk(r, depth + 1);
      } else if (e.isFile()) {
        out.push({ path: r, dir: false, size: fs.statSync(path.join(dir, e.name)).size, protected: isProtected(r) });
      }
    }
  };
  walk(root, 0);
  return out;
}

const changed = async (project: Project, message: string, rels: string[]) => {
  await commitProject(project.id, message, [...new Set(rels.map((r) => r.split('/')[0]))]).catch(() => undefined);
  notifyProject(project.id, 'builder.updated');
};

export function registerConfigRoutes(): void {
  get('/api/projects/:pid/config/files', (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid);
    const root = ctx.query.get('root') || '.claude';
    if (!CONFIG_ROOTS.includes(root as any)) throw badRequest('Choose .claude or .kiro');
    return { root, files: listConfig(project, root), canChangeProtected: Boolean(ctx.user!.is_admin) };
  });

  get('/api/projects/:pid/config/file', (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid);
    const rel = checkPath(ctx.query.get('path'));
    const file = abs(project, rel);
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) throw notFound('File not found');
    const buf = fs.readFileSync(file);
    if (buf.length > MAX_FILE) throw badRequest('That file is larger than 512 KB, so it cannot be edited here');
    if (buf.includes(0)) return { path: rel, binary: true, content: null, protected: isProtected(rel) };
    return { path: rel, binary: false, content: buf.toString('utf8'), protected: isProtected(rel) };
  });

  put('/api/projects/:pid/config/file', async (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid, 'editor');
    const body = await ctx.json();
    const rel = checkPath(body.path);
    mustChange(ctx, rel);
    const content = typeof body.content === 'string' ? body.content : '';
    checkContent(rel, content);
    mustKeepAgentCommands(ctx, project, rel, content);
    const file = abs(project, rel);
    if (fs.existsSync(file) && fs.statSync(file).isDirectory()) throw badRequest('That is a folder');
    const existed = fs.existsSync(file);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    await changed(project, `${existed ? 'Edit' : 'Add'} ${rel} (${ctx.user!.name})`, [rel]);
    return { ok: true, path: rel };
  });

  post('/api/projects/:pid/config/folder', async (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid, 'editor');
    const rel = checkPath((await ctx.json()).path);
    mustChange(ctx, rel);
    fs.mkdirSync(abs(project, rel), { recursive: true });
    // Git does not track empty folders; a .gitkeep keeps the new folder in the project's history.
    const keep = path.join(abs(project, rel), '.gitkeep');
    if (!fs.readdirSync(path.dirname(keep)).length) fs.writeFileSync(keep, '');
    await changed(project, `Add folder ${rel} (${ctx.user!.name})`, [rel]);
    return { ok: true, path: rel };
  });

  del('/api/projects/:pid/config/file', async (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid, 'editor');
    const rel = checkPath(ctx.query.get('path'));
    if (rel.split('/').length < 2) throw badRequest('The .claude and .kiro folders themselves cannot be deleted');
    const file = abs(project, rel);
    if (!fs.existsSync(file)) throw notFound('Not found');
    // Deleting a folder deletes what is in it, so it needs the rights for everything inside.
    if (fs.statSync(file).isDirectory()) {
      for (const e of listConfig(project, rel)) mustChange(ctx, e.path);
    }
    mustChange(ctx, rel);
    fs.rmSync(file, { recursive: true, force: true });
    await changed(project, `Delete ${rel} (${ctx.user!.name})`, [rel]);
    return { ok: true };
  });

  get('/api/projects/:pid/config/export', async (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid);
    const root = ctx.query.get('root') || '.claude';
    if (!CONFIG_ROOTS.includes(root as any)) throw badRequest('Choose .claude or .kiro');
    const zip = new JSZip();
    for (const e of listConfig(project, root)) if (!e.dir) zip.file(e.path, fs.readFileSync(abs(project, e.path)));
    const buf = await zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
    return sendFile(ctx.res, buf, 'application/zip', `${project.slug}${root}.zip`);
  });

  // Import a zip into .claude or .kiro: files are added or replaced, nothing is deleted. Entries may be stored with or
  // without the root folder name (".claude/agents/x.md" or "agents/x.md").
  put('/api/projects/:pid/config/import', async (ctx) => {
    const { project } = requireProject(ctx, ctx.params.pid, 'editor');
    const root = ctx.query.get('root') || '.claude';
    if (!CONFIG_ROOTS.includes(root as any)) throw badRequest('Choose .claude or .kiro');
    const zip = await JSZip.loadAsync(await ctx.raw(MAX_IMPORT)).catch(() => {
      throw badRequest('That is not a zip file');
    });
    const plan: { rel: string; content: string }[] = [];
    let total = 0;
    for (const entry of Object.values(zip.files)) {
      if (entry.dir) continue;
      // JSZip quietly strips "../" from names; a zip that tries to climb out is refused rather than renamed.
      const original = String((entry as any).unsafeOriginalName ?? entry.name).replace(/\\/g, '/');
      if (original.startsWith('/') || /^[A-Za-z]:/.test(original) || original.split('/').includes('..')) throw badRequest(`The zip entry "${original}" points outside the folder`);
      const name = entry.name.replace(/\\/g, '/').replace(/^\/+/, '');
      if (name.split('/').some((x) => x.startsWith('__MACOSX') || x === '.DS_Store')) continue;
      const rel = checkPath(name.startsWith(`${root}/`) ? name : `${root}/${name}`);
      const content = await entry.async('string');
      total += Buffer.byteLength(content);
      if (total > MAX_IMPORT) throw badRequest('The files in that zip are larger than 20 MB in total');
      checkContent(rel, content);
      mustChange(ctx, rel);
      mustKeepAgentCommands(ctx, project, rel, content);
      plan.push({ rel, content });
    }
    if (!plan.length) throw badRequest('That zip has no files');
    if (plan.length > MAX_FILES) throw badRequest(`At most ${MAX_FILES} files`);
    // Everything is checked before anything is written.
    for (const p of plan) {
      const file = abs(project, p.rel);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, p.content);
    }
    await changed(project, `Import ${plan.length} file${plan.length === 1 ? '' : 's'} into ${root} (${ctx.user!.name})`, [root]);
    return { ok: true, files: plan.map((p) => p.rel) };
  });
}
