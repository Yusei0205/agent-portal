/**
 * Learn routes: docs, quizzes (take + attempts) and learning paths with progress, on the learn repository.
 */
import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { createTestServer, cleanup, fetchJson } from './fixtures.ts';
import { getLearnRepository } from '../server/repositories/learn.ts';

let baseUrl = '';
let cookie = '';
let projectId = '';

const j = async (path: string, method = 'GET', body?: unknown) =>
  (await fetchJson(baseUrl, path, { method, body, cookie })) as { status: number; body: any };

describe('learn routes', () => {
  before(async () => {
    const srv = await createTestServer();
    baseUrl = srv.baseUrl;
    const setup = await fetchJson(baseUrl, '/api/auth/setup', {
      method: 'POST',
      body: { email: `learn-${Date.now()}@example.com`, name: 'Admin', password: 'password1234', provider: 'demo' },
    });
    cookie = setup.cookie ?? '';
    const p = await fetchJson(baseUrl, '/api/projects', { method: 'POST', body: { name: 'Learn' }, cookie });
    projectId = ((p.body as any).project as any).id as string;
  });
  after(cleanup);

  it('doc lifecycle: create, edit, publish, read, unpublish, delete', async () => {
    const c = await j(`/api/projects/${projectId}/learn/docs`, 'POST', { title: 'Onboarding', doc_type: 'overview' });
    assert.equal(c.status, 201, JSON.stringify(c.body));
    const id = c.body.doc.id as string;
    assert.equal(c.body.doc.published, false);

    const patch = await j(`/api/learn/docs/${id}`, 'PATCH', { title: 'Onboarding v2' });
    assert.equal(patch.body.doc.title, 'Onboarding v2');

    assert.equal((await j(`/api/learn/docs/${id}/publish`, 'POST', {})).body.doc.published, true);
    assert.equal((await j(`/api/learn/docs/${id}/read`, 'POST', {})).status, 200);
    const got = await j(`/api/learn/docs/${id}`);
    assert.equal(got.body.doc.read, true);

    const list = await j(`/api/projects/${projectId}/learn/docs`);
    assert.equal(list.body.docs.length, 1);
    assert.equal((await j(`/api/learn/docs/${id}/unpublish`, 'POST', {})).status, 200);
    assert.equal((await j(`/api/learn/docs/${id}`, 'DELETE')).status, 200);
    assert.equal((await j(`/api/learn/docs/${id}`)).status, 404);
  });

  it('quiz attempts are graded and listed; path progress follows', async () => {
    const doc = await j(`/api/projects/${projectId}/learn/docs`, 'POST', { title: 'Doc for quiz' });
    const docId = doc.body.doc.id as string;
    await j(`/api/learn/docs/${docId}/publish`, 'POST', {});

    const q = await j(`/api/projects/${projectId}/learn/quizzes`, 'POST', { title: 'Quiz', learnDocId: docId });
    assert.equal(q.status, 201, JSON.stringify(q.body));
    const quizId = q.body.quiz.id as string;
    const bad = await j(`/api/projects/${projectId}/learn/quizzes`, 'POST', { title: 'Q2', learnDocId: 'nope' });
    assert.equal(bad.status, 400);

    // Questions are normally generated by an agent; set them directly.
    await getLearnRepository().updateQuiz(quizId, {
      questions: JSON.stringify([
        { id: 'q1', type: 'mcq', question: '1+1?', options: ['1', '2'], answer: '2' },
        { id: 'q2', type: 'mcq', question: '2+2?', options: ['3', '4'], answer: '4' },
      ]),
    });
    await j(`/api/learn/quizzes/${quizId}/publish`, 'POST', {});

    const attempt = await j(`/api/learn/quizzes/${quizId}/attempts`, 'POST', { answers: { q1: '2', q2: '4' } });
    assert.equal(attempt.status, 201, JSON.stringify(attempt.body));
    assert.equal(attempt.body.attempt.score, 2);
    assert.equal(attempt.body.attempt.passed, true);

    const attempts = await j(`/api/learn/quizzes/${quizId}/attempts`);
    assert.equal(attempts.body.attempts.length, 1);
    assert.equal(attempts.body.attempts[0].score, 2);
    assert.ok(attempts.body.attempts[0].name);

    const path = await j(`/api/projects/${projectId}/learn/paths`, 'POST', {
      title: 'Path', publish: true,
      steps: [{ type: 'doc', id: docId }, { type: 'quiz', id: quizId }],
    });
    assert.equal(path.status, 201, JSON.stringify(path.body));
    assert.equal(path.body.path.progress, 50); // quiz passed, doc not yet read
    await j(`/api/learn/docs/${docId}/read`, 'POST', {});
    const list = await j(`/api/projects/${projectId}/learn/paths`);
    assert.equal(list.body.paths[0].progress, 100);

    const progress = await j(`/api/projects/${projectId}/learn/progress`);
    assert.equal(progress.status, 200);
    assert.equal(progress.body.members[0].quizzesPassed, 1);
    assert.equal(progress.body.members[0].progress[path.body.path.id], 100);

    assert.equal((await j(`/api/learn/paths/${path.body.path.id}`, 'DELETE')).status, 200);
  });
});
